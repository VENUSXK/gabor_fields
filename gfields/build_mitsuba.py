"""Compile the Mitsuba 3 fork and wire it into a target interpreter.

Invoked by ``install.sh`` / ``install.ps1`` (run with the uv ``.venv`` python),
but usable standalone:

    python gfields/build_mitsuba.py --python .venv/Scripts/python.exe

Steps: configure CMake against the given interpreter, enable exactly the
variants the codebase uses (``scalar_rgb``, ``cuda_ad_rgb``), build Release, and
drop a ``.pth`` in the interpreter's site-packages so ``import mitsuba`` /
``import drjit`` resolve to the fresh build (bundled DLLs included). This is the
reproducible replacement for the hand-placed ``_mitsuba39_default.pth`` that the
stale ``build_39`` shipped with.
"""
from __future__ import annotations

import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MITSUBA_SRC = REPO / "submodules" / "mitsuba3"
DEFAULT_VARIANTS = ["scalar_rgb", "cuda_ad_rgb"]  # matches the validated build_39


def run(cmd: list[str], **kw) -> None:
    print("  $", " ".join(str(c) for c in cmd), flush=True)
    subprocess.run(cmd, check=True, **kw)


def detect_generator() -> tuple[str, bool]:
    """Return (cmake -G value, is_multi_config)."""
    if os.name == "nt":
        return "Visual Studio 17 2022", True          # validated on this machine
    if shutil.which("ninja"):
        return "Ninja", False
    return "Unix Makefiles", False


def write_variants(build_dir: Path, variants: list[str]) -> None:
    """Seed build/mitsuba.conf from the template with exactly `variants` enabled.

    Mitsuba only copies the template if build/mitsuba.conf is absent, so we place
    a patched copy up front and CMake picks it up on the first configure.
    """
    template = MITSUBA_SRC / "resources" / "mitsuba.conf.template"
    conf = build_dir / "mitsuba.conf"
    build_dir.mkdir(parents=True, exist_ok=True)
    text = template.read_text()
    enabled = ",\n        ".join(f'"{v}"' for v in variants)
    text = re.sub(r'"enabled"\s*:\s*\[[^\]]*\]',
                  f'"enabled": [\n        {enabled}\n    ]', text, count=1)
    conf.write_text(text)
    print(f"  enabled variants -> {', '.join(variants)}")


def site_packages(python: Path) -> Path:
    out = subprocess.run(
        [str(python), "-c", "import sysconfig; print(sysconfig.get_path('purelib'))"],
        check=True, capture_output=True, text=True).stdout.strip()
    return Path(out)


def python_build_dir(build_dir: Path, multi_config: bool) -> Path:
    for cand in ((build_dir / "Release" / "python"), (build_dir / "python")):
        if (cand / "mitsuba").is_dir():
            return cand
    # Fall back to the layout implied by the generator even if not yet populated.
    return (build_dir / "Release" / "python") if multi_config else (build_dir / "python")


def write_pth(python: Path, pkg_dir: Path, build_dir: Path) -> None:
    sp = site_packages(python)
    dll_dirs = [str(pkg_dir), str(build_dir / "bin" / "Release"), str(build_dir / "Release")]
    boot = f'''# Auto-generated by gfields/build_mitsuba.py. Routes `import mitsuba` / `import
# drjit` to the locally compiled fork at:
#   {build_dir}
# Delete this and _volprim_mitsuba.pth to detach the build from this interpreter.
import os, sys
_PKG = r"{pkg_dir}"
if os.path.isdir(_PKG):
    for _d in [r"{dll_dirs[0]}", r"{dll_dirs[1]}", r"{dll_dirs[2]}"]:
        try:
            if os.path.isdir(_d):
                os.add_dll_directory(_d)
        except (OSError, AttributeError):
            pass
    if _PKG not in sys.path:
        sys.path.insert(0, _PKG)
'''
    (sp / "_volprim_mitsuba.py").write_text(boot)
    (sp / "_volprim_mitsuba.pth").write_text("import _volprim_mitsuba\n")
    print(f"  wired into {sp}")


def validate(python: Path) -> None:
    code = (
        "import mitsuba as mi, drjit as dr;"
        "mi.set_variant('cuda_ad_rgb');"
        "print('mitsuba', mi.__version__, '| drjit', dr.__version__, '| variant', mi.variant())"
    )
    print("Validating import ...")
    run([str(python), "-c", code])


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--python", required=True, help="Interpreter to build against and wire into")
    ap.add_argument("--build-dir", default=str(MITSUBA_SRC / "build_uv"))
    ap.add_argument("--variants", default=",".join(DEFAULT_VARIANTS),
                    help="Comma-separated variants (default: scalar_rgb,cuda_ad_rgb)")
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    ap.add_argument("--skip-config", action="store_true")
    ap.add_argument("--skip-build", action="store_true")
    ap.add_argument("--skip-wire", action="store_true")
    args = ap.parse_args()

    python = Path(args.python).resolve()
    build_dir = Path(args.build_dir).resolve()
    variants = [v.strip() for v in args.variants.split(",") if v.strip()]
    generator, multi_config = detect_generator()

    if not (MITSUBA_SRC / "CMakeLists.txt").is_file():
        sys.exit(f"Mitsuba source not found at {MITSUBA_SRC}. "
                 "Run: git submodule update --init --recursive submodules/mitsuba3")

    print(f"== Building Mitsuba fork ==\n  source : {MITSUBA_SRC}\n  build  : {build_dir}"
          f"\n  python : {python}\n  gen    : {generator}\n  variants: {', '.join(variants)}")

    if not args.skip_config:
        write_variants(build_dir, variants)
        cfg = ["cmake", "-S", str(MITSUBA_SRC), "-B", str(build_dir), "-G", generator,
               f"-DPython_EXECUTABLE={python}"]
        if not multi_config:
            cfg.append("-DCMAKE_BUILD_TYPE=Release")
        run(cfg)

    if not args.skip_build:
        build = ["cmake", "--build", str(build_dir), "--parallel", str(args.jobs)]
        if multi_config:
            build += ["--config", "Release"]
        run(build)

    pkg = python_build_dir(build_dir, multi_config)
    if not (pkg / "mitsuba").is_dir():
        sys.exit(f"Build finished but no mitsuba package at {pkg} — check the build log.")

    if not args.skip_wire:
        write_pth(python, pkg, build_dir)
    validate(python)
    print("Done. Mitsuba fork built and wired.")


if __name__ == "__main__":
    main()
